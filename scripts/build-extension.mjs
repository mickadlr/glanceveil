import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.includes("--check");
const bundles = [
  {
    output: "browser-extension/content-bundle.js",
    inputs: [
      "browser-extension/shared/core.js",
      "browser-extension/shared/state.js",
      "browser-extension/shared/gregg.js",
      "browser-extension/content.js"
    ]
  },
  {
    output: "browser-extension/google-docs-bundle.js",
    inputs: [
      "browser-extension/shared/core.js",
      "browser-extension/google-docs-main.js"
    ]
  }
];

async function bundle({ output, inputs }) {
  const sections = await Promise.all(inputs.map(async (input) => {
    const source = await readFile(path.join(root, input), "utf8");
    return `// Source: ${input}\n${source.trimEnd()}`;
  }));
  const generated =
    "// Generated by `npm run build:extension`. Do not edit this file directly.\n\n" +
    `${sections.join("\n\n")}\n`;
  const outputPath = path.join(root, output);

  if (!checkOnly) {
    await writeFile(outputPath, generated);
    return;
  }

  let current = "";
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    // The mismatch error below includes the command needed to generate it.
  }
  if (current !== generated) {
    throw new Error(`${output} is stale. Run npm run build:extension.`);
  }
}

await Promise.all(bundles.map(bundle));
